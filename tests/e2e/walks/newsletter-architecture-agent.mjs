// Newsletter Architecture Agent (operator page): the intake and its gate,
// every error the page can show, generation, the architecture tab, the four
// issues and their three tabs, the review loop to its third round, copy, and
// the .txt pack read back and compared whole, in both languages.
import fs from 'node:fs';

export const page = 'newsletter-architecture-agent.html';
export const title = 'intake, errors, architecture, four issues, review to round 3, copy, .txt pack';

const sleep = ms => new Promise(r => setTimeout(r, ms));
const flat = s => String(s).replace(/\s+/g, ' ').trim();

// ── What the model answers ──────────────────────────────────────────────
// The page promises the first 4 issues, so the answer holds exactly four.
// The issue types are four of the values the prompt lists in English: the
// page paints them in French. The second section of every issue has no
// name, so the page falls back to "Section 2".
const BRAND = 'Maison Levain';
const TYPES = ['Manifesto', 'Deep dive', 'Framework', 'Story'];
const issue = n => ({
  issueNumber: n, issueType: TYPES[n - 1],
  subjectLine: `Issue ${n} subject`, subjectLineVariants: [`Issue ${n} variant A`, `Issue ${n} variant B`],
  previewText: `Issue ${n} preview`, premise: `Issue ${n} premise`, readTime: '4 min read',
  strategicPurpose: `Issue ${n} purpose`, bestSendTime: 'Tuesday 7am',
  opening: `Issue ${n} opening, first paragraph.\n\nIssue ${n} opening, second paragraph.`,
  sections: [{ sectionName: `Issue ${n} proof`, content: `Issue ${n} proof, written out` }, { content: `Issue ${n} second part, written out` }],
  closing: `Issue ${n} closing`, ps: `Issue ${n} afterthought`,
  growthHook: `Issue ${n} forward prompt`, repurposeAngles: [`Issue ${n} as a post`, `Issue ${n} as a video`],
});
const answer = () => ({
  architecture: {
    name: 'The Crumb', tagline: 'Bread, once a week.', nameRationale: 'Why the name holds', positioningStatement: 'What the letter is for',
    format: 'How an issue is built', sections: ['The proof', 'The crumb'], cadence: 'Tuesday morning',
    idealReader: 'Who subscribes', toneRegister: 'How it sounds', signatureElements: ['An opening ritual', 'A sign-off line'],
    growthStrategy: 'How the list grows', platformRecommendation: 'Where it is sent from', welcomeEmailOutline: 'What the first emails do',
  },
  issues: [1, 2, 3, 4].map(issue),
});

// ── The pack, restated here line for line ───────────────────────────────
const WORDS = {
  en: {
    title: n => `NEWSLETTER PACK - ${n}`, by: 'Generated by BrandOS - Newsletter Architecture Agent', arch: 'ARCHITECTURE',
    name: v => `Name: ${v}`, tagline: v => `Tagline: ${v}`, cadence: v => `Cadence: ${v}`,
    issue: (n, t) => `ISSUE ${n} - ${t}`, subject: v => `Subject: ${v}`, preview: v => `Preview: ${v}`,
    opening: 'OPENING:', closing: 'CLOSING:', types: {},
  },
  fr: {
    title: n => `PACK NEWSLETTER · ${n}`, by: 'Généré par BrandOS · Agent d’architecture de newsletter', arch: 'ARCHITECTURE',
    name: v => `Nom : ${v}`, tagline: v => `Signature : ${v}`, cadence: v => `Cadence : ${v}`,
    issue: (n, t) => `NUMÉRO ${n} · ${t}`, subject: v => `Objet : ${v}`, preview: v => `Aperçu : ${v}`,
    opening: 'OUVERTURE :', closing: 'CONCLUSION :',
    types: { Manifesto: 'Manifeste', 'Deep dive': 'Analyse approfondie', Framework: 'Cadre', Story: 'Récit' },
  },
};
function pack(lang, a, kept) {
  const L = WORDS[lang];
  const lines = [L.title(a.name), L.by, '', L.arch, '='.repeat(60), L.name(a.name), L.tagline(a.tagline), L.cadence(a.cadence), ''];
  for (const x of kept) {
    lines.push('='.repeat(60), L.issue(String(x.issueNumber).padStart(2, '0'), L.types[x.issueType] || x.issueType), L.subject(x.subjectLine), L.preview(x.previewText), '');
    lines.push(L.opening, x.opening, '');
    x.sections.forEach((s, i) => lines.push(`[${s.sectionName || `Section ${i + 1}`}]`, s.content, ''));
    lines.push(L.closing, x.closing, '', `P.S. ${x.ps}`, '');
  }
  return lines.join('\n');
}
const firstDifference = (got, want) => {
  const a = got.split('\n'), b = want.split('\n');
  for (let i = 0; i < Math.max(a.length, b.length); i++) if (a[i] !== b[i]) return `line ${i + 1}: got ${JSON.stringify(a[i])}, expected ${JSON.stringify(b[i])}`;
  return 'same lines, different line endings';
};

export async function walk(w) {
  const p = w.page;
  const main = { within: '#root main' };
  const calls = [];                       // every model call the page made
  let reply = null;                       // a one-off answer for the next generation
  const loops = [];
  p.on('console', m => { if (/Maximum update depth/.test(m.text())) loops.push(m.text()); });

  // w.see, w.click and w.locate cannot find French text that holds a no-break
  // space ("Envoi recommandé :"): the helper turns it into a plain space on
  // its side and XPath does not on the page's side. Text with one is looked
  // up here; everything else goes through the helper as usual.
  const locate = async (english, opts = {}) => {
    const painted = opts.painted ? english : await w.say(english);
    if (!painted.includes(' ')) return w.locate(english, opts);
    const text = flat(painted);
    const lit = text.includes("'") ? `concat('${text.split("'").join(`', "'", '`)}')` : `'${text}'`;
    return (opts.within ? p.locator(opts.within) : p)
      .locator(`xpath=.//*[text()[normalize-space(translate(., ' ', ' '))=${lit}]]`).filter({ visible: true }).first();
  };
  // A failure names the text it was after, so the report says what was missing.
  const named = (what, english, e) => new Error(`${what} ${JSON.stringify(english)}: ${String(e.message).split('\n')[0]}`);
  const see = async (english, opts = {}) => {
    try { await (await locate(english, opts)).waitFor({ state: 'visible', timeout: opts.timeout ?? 8000 }); }
    catch (e) { throw named('did not see', english, e); }
  };
  const click = async (english, opts = {}) => {
    try { await (await locate(english, opts)).click({ timeout: opts.timeout ?? 8000 }); }
    catch (e) { throw named('could not click', english, e); }
    await p.waitForTimeout(opts.wait ?? 250);
  };

  // A field is the input, textarea or select that follows its label.
  const field = async label => (await locate(label)).locator('xpath=following-sibling::*[self::input or self::textarea or self::select][1]');
  const go = p.locator('#root main button.btn-primary').first();      // on the intake, the only one
  const shown = '.qb-review_item:visible';                             // the one issue on screen
  const inView = { within: shown };
  const pick = async i => { await p.locator('#root .issue-card').nth(i).click(); await p.waitForTimeout(200); };
  const summary = async () => flat(await p.locator('.qb-review > div:first-child > div:first-child > div:nth-child(2)').textContent());
  const counts = async (a, b, c) => `${a} ${await w.say('approved ·')} ${b} ${await w.say('pending ·')} ${c} ${await w.say('removed')}`;
  const clipboard = () => p.evaluate(() => navigator.clipboard.readText());
  const failOnce = (status, body, type = 'application/json') =>
    p.context().route('**/api/claude', async route => { await sleep(500); await route.fulfill({ status, contentType: type, body }); }, { times: 1 });

  await w.mockModel(async (body, route) => {
    const lang = route.request().headers()['x-qb-lang'];
    const text = body.messages && body.messages[0] && body.messages[0].content || '';
    if (/content revision agent/.test(body.system || '')) {
      const item = JSON.parse(/^You produced this content piece: ([\s\S]*?)\n\nThe user requests this revision: /.exec(text)[1]);
      const ask = /The user requests this revision: ([\s\S]*?)\n\nReturn ONLY/.exec(text)[1];
      calls.push({ kind: 'revise', lang, item, ask, max: body.max_tokens });
      await sleep(600);
      if (/break/.test(ask)) return 'Sorry, here is some prose and no JSON.';
      const n = /round (\d)/.exec(ask)[1];
      return { ...item, subjectLine: `Issue ${item.issueNumber}, revision ${n}`, opening: `Issue ${item.issueNumber} opening, revision ${n}.` };
    }
    calls.push({ kind: 'generate', lang, text, max: body.max_tokens });
    await sleep(600);
    const out = reply || answer();
    reply = null;
    return out;
  });

  await w.step('open', async () => {
    await w.open();
    await see('Build Newsletter System →', { timeout: 45000 });
    await see('Newsletter Architecture Agent', main);
    await see('Phase 03 - Content Creation');
    w.check(await p.title() === await w.say('Newsletter Architecture Agent · BrandOS'), `title tag is ${JSON.stringify(await p.title())}`);
    // The meta description used to say Phase 04 while the page says Phase 03.
    const meta = await p.locator('meta[name="description"]').getAttribute('content');
    w.check(meta === await w.say('Design a newsletter that compounds. Rhythm, segments, and signature sections drawn from your Brand Profile. Phase 03 inside BrandOS.'), `the meta description reads ${JSON.stringify(meta)}`);
    // The THEME button changed nothing and is gone.
    w.check(await p.locator('#root button').filter({ hasText: /^\s*TH[EÈ]ME\s*$/ }).count() === 0, 'the dead THEME button is back');
  });

  await w.step('intake: the button opens only when the six required fields are filled', async () => {
    w.check(await go.isDisabled(), 'Build is enabled on an empty form');
    w.check(await (await field('Brand Name *')).getAttribute('placeholder') === await w.say('The brand behind the newsletter'), 'input placeholder is not in the page language');
    w.check(await (await field('Primary Persona *')).getAttribute('placeholder') === await w.say('Who subscribes - role, struggle, desire. Specific.'), 'textarea placeholder is not in the page language');
    await w.fill(await field('Brand Name *'), BRAND);
    await w.fill(await field('Brand Essence *'), 'Bread, and nothing else.');
    const force = await field('Natural Force *');
    await force.selectOption('The Sunrise');
    w.check(flat(await force.locator('option:checked').innerText()) === await w.say('The Sunrise'), 'the chosen force is not painted in the page language');
    await (await field('Primary Archetype *')).selectOption('The Caregiver');
    await w.fill(await field('Primary Persona *'), 'Parents who cook on Sunday.');
    w.check(await go.isDisabled(), 'Build is enabled with the offer still empty');
    await w.fill(await field('Core Offer *'), 'A weekly bread subscription.');
    w.check(await go.isEnabled(), 'Build is still disabled with every required field filled');
    await (await field('Primary Archetype *')).selectOption('');
    w.check(await go.isDisabled(), 'Build stays enabled after a required choice is cleared');
    await (await field('Primary Archetype *')).selectOption('The Caregiver');
  });

  const fails = async (name, arm, message) => {
    await w.step(`error: ${name}`, async () => {
      await arm();
      await go.click();
      await see('Agent Synthesizing');
      await see(message, { timeout: 10000 });
      w.check(await (await field('Brand Name *')).inputValue() === BRAND, 'the form was emptied by the error');
      w.check(await go.isEnabled(), 'Build is not available after the error');
    });
  };
  const gone = 'The agent could not finish. Nothing was generated. Try again in a moment.';
  w.note('Overloaded, try later');
  w.note('Refused upstream');
  await fails('the server answers 500 with a message', () => failOnce(500, JSON.stringify({ error: { message: 'Overloaded, try later' } })), 'Agent error: Overloaded, try later');
  await fails('the server answers 500 with nothing', () => failOnce(500, '{}'), 'Agent error: API error: HTTP 500');
  await fails('the gateway times out', () => failOnce(504, 'timeout', 'text/plain'), gone);
  await fails('the answer is not JSON', () => failOnce(200, '<html>oops</html>', 'text/html'), gone);
  await fails('the answer is an error', () => failOnce(200, JSON.stringify({ error: { message: 'Refused upstream' } })), 'Agent error: Refused upstream');
  await fails('the model writes prose', async () => { reply = 'Here is your newsletter, in prose.'; }, gone);
  // This used to open an empty "System Complete" screen.
  await fails('the answer holds no issue', async () => { reply = { architecture: answer().architecture, issues: [] }; }, gone);
  await fails('the answer holds no architecture', async () => { reply = { issues: answer().issues }; }, gone);

  await w.step('generate', async () => {
    await go.click();
    await see('Agent Synthesizing');
    await see('Scanning Quantum Brand Profile...');
    await see('> Executing 4-issue content generation');
    await see('System Complete', { timeout: 10000 });
    await see('The Crumb', { painted: true, within: '#root main' });
    await see('Bread, once a week.', { painted: true });
    const call = calls.filter(c => c.kind === 'generate').pop();
    w.check(call.lang === w.lang, `the model was asked in ${JSON.stringify(call.lang)}, not ${w.lang}`);
    // What goes to the model stays English whatever the page shows.
    w.check(call.text.includes('Natural Force: The Sunrise') && call.text.includes('Archetype: The Caregiver'), 'the prompt did not carry the stored English values');
    w.check(call.text.includes(`Brand: ${BRAND}`) && call.text.includes('Author: [Author]'), 'the prompt did not carry the intake');
  });

  await w.step('architecture', async () => {
    for (const label of ['Newsletter Positioning', 'Name + Tagline', 'Format + Structure', 'Cadence', 'Ideal Reader', 'Tone + Register', 'Signature Elements', 'Growth Strategy', 'Platform Recommendation', 'Welcome Sequence Outline']) await see(label, main);
    for (const text of ['Why the name holds', 'How an issue is built', 'The crumb', 'Tuesday morning', 'Who subscribes', 'How it sounds', 'A sign-off line', 'How the list grows', 'Where it is sent from', 'What the first emails do']) await see(text, { painted: true });
  });

  await w.step('four issues, one on screen, under review', async () => {
    await click('4 Issues');
    await see('The Sequence');
    await see('Content Review');
    w.check(await p.locator('#root .issue-card').count() === 4, 'the sequence does not hold 4 issues');
    w.check(await p.locator('.qb-review_item').count() === 4 && await p.locator(shown).count() === 1, 'the review does not show one issue of four');
    w.check(await summary() === await counts(0, 4, 0), `summary reads ${JSON.stringify(await summary())}`);
    await see('ISSUE', inView);
    await see('Issue 1 subject', { painted: true, within: shown });
    await see(await w.say('Manifesto'), { painted: true, within: shown });
    await see('Pending Review', inView);
  });

  await w.step('issue 1: full issue, subject and meta, growth engine, and copy', async () => {
    await see('Opening - the hook', inView);                       // open from the start
    await click('COPY', inView);
    await see('✓ COPIED', inView);
    w.check(await clipboard() === issue(1).opening, `the clipboard holds ${JSON.stringify(await clipboard())}`);
    await click('Issue 1 proof', { painted: true, within: shown });
    await see('Issue 1 proof, written out', { painted: true, within: shown });
    await click('Section 2', inView);                              // the section with no name
    await see('Issue 1 second part, written out', { painted: true, within: shown });
    await see('Closing + CTA', inView);
    await see('P.S.', inView);

    await click('Subject + Meta', inView);
    for (const label of ['Subject line', 'A/B variants', 'Preview text (inbox snippet)', 'Strategic purpose in the sequence', 'Recommended delivery:']) await see(label, inView);
    for (const text of ['Issue 1 variant B', 'Issue 1 preview', 'Issue 1 purpose', 'Tuesday 7am']) await see(text, { painted: true, within: shown });

    await click('Growth Engine', inView);
    await see('Referral / forward hook', inView);
    await see('Repurpose angles', inView);
    await see('Issue 1 forward prompt', { painted: true, within: shown });
    await see('Issue 1 as a video', { painted: true, within: shown });
    await click('Full Issue', inView);
  });

  await w.step('the sequence picks the issue', async () => {
    await pick(1);
    await see('Issue 2 subject', { painted: true, within: shown });
    await see(await w.say('Deep dive'), { painted: true, within: shown });
    w.check(await p.locator(shown).count() === 1, 'more than one issue on screen');
    w.check(!flat(await p.locator(shown).innerText()).includes('Issue 1 subject'), 'issue 1 is still on screen');
    await pick(0);
  });

  await w.step('review: three rounds on one issue, then no fourth', async () => {
    for (const round of [1, 2, 3]) {
      await click('↻ Revise', inView);
      const head = await locate('Revision Request', inView);
      w.check(flat(await head.textContent()) === `${await w.say('Revision Request')} ${round}/3`, `the request header reads ${JSON.stringify(flat(await head.textContent()))}`);
      const box = p.locator(shown).locator('textarea');
      if (round === 1) w.check(await box.getAttribute('placeholder') === await w.say("What should change? Be specific: e.g. 'Make the hook more direct' or 'Remove the question format'"), 'the request placeholder is not in the page language');
      await w.fill(box, `Warmer, round ${round}`);
      await click('Submit Revision →', { within: shown, wait: 50 });
      await see('Revising…', inView);
      await see('Generating revision…', inView);
      await see('Revised - Review Again', inView);
      await see(`(ROUND ${round}/3)`, inView);
      await see(`Issue 1, revision ${round}`, { painted: true, within: shown });
      // The sequence beside it follows the revision.
      await see(`Issue 1, revision ${round}`, { painted: true, within: '#root .issue-card >> nth=0' });
    }
    w.check(await (await locate('↻ Revise', inView)).count() === 0, 'a fourth revision is offered');
    w.check(await (await locate('✓ Approve', inView)).count() === 1, 'Approve is gone after the third round');
    const asks = calls.filter(c => c.kind === 'revise');
    w.check(asks.length === 3, `${asks.length} revision calls for three rounds`);
    w.check(asks.every(c => c.lang === w.lang), 'a revision was not asked in the page language');
    w.check(asks[2] && asks[2].item.subjectLine === 'Issue 1, revision 2' && asks[2].ask === 'Warmer, round 3', 'the third round did not start from the second');
    // A whole issue does not fit in the 1000 tokens a short post gets.
    w.check(asks.every(c => c.max === 4000), `revision budget was ${asks.map(c => c.max).join(', ')}`);
  });

  await w.step('review: cancel, a failed revision, remove, approve, undo', async () => {
    await pick(1);
    await click('↻ Revise', inView);
    await click('Cancel', inView);
    w.check(await p.locator(shown).locator('textarea').count() === 0, 'Cancel left the request open');

    await click('↻ Revise', inView);
    await w.fill(p.locator(shown).locator('textarea'), 'Please break');
    await click('Submit Revision →', { within: shown, wait: 50 });
    await see('Revising…', inView);
    await see('Revision failed - try again', inView);
    await see('Issue 2 subject', { painted: true, within: shown });
    await click('↻ Revise', inView);
    w.check(flat(await (await locate('Revision Request', inView)).textContent()).endsWith(' 1/3'), 'a failed revision used up a round');
    await click('Cancel', inView);

    await pick(3);
    await click('× Remove', inView);
    await see('Removed', inView);
    await p.waitForTimeout(300);
    w.check(await p.locator('#root .issue-card').nth(3).evaluate(el => getComputedStyle(el).opacity) === '0.4', 'the removed issue is not dimmed in the sequence');

    await pick(0);
    await click('✓ Approve', inView);
    await see('✓ Approved', inView);
    w.check(await summary() === await counts(1, 2, 1), `summary reads ${JSON.stringify(await summary())}`);
    await click('Undo', inView);
    await see('Pending Review', inView);
    w.check(await summary() === await counts(0, 3, 1), `summary reads ${JSON.stringify(await summary())}`);
  });

  await w.step('the review survives a change of tab', async () => {
    await click('Architecture', main);
    await see('Newsletter Positioning', main);
    await click('4 Issues');
    await see('Issue 1, revision 3', { painted: true, within: shown });
    w.check(await summary() === await counts(0, 3, 1), `after the round trip the summary reads ${JSON.stringify(await summary())}`);
  });

  await w.step('the .txt pack holds what the review holds', async () => {
    const [dl] = await Promise.all([p.waitForEvent('download', { timeout: 10000 }), click('Export Pack')]);
    const file = { name: dl.suggestedFilename(), text: fs.readFileSync(await dl.path(), 'utf8') };
    const data = answer();
    const kept = data.issues.filter(x => x.issueNumber !== 4)
      .map(x => x.issueNumber === 1 ? { ...x, subjectLine: 'Issue 1, revision 3', opening: 'Issue 1 opening, revision 3.' } : x);
    const want = pack(w.lang, data.architecture, kept);
    w.check(file.name === 'maison-levain-newsletter-pack.txt', `the file is named ${JSON.stringify(file.name)}`);
    w.check(file.text === want, `the pack differs at ${firstDifference(file.text, want)}`);
    w.check(!file.text.includes('Issue 4'), 'a removed issue is in the pack');
    w.check(file.text.includes('[Section 2]') && !file.text.includes('undefined'), 'a section with no name is not written as "Section 2"');
  });

  await w.step('approve everything: all done, and the page comes to rest', async () => {
    for (const i of [0, 1, 2]) { await pick(i); await click('✓ Approve', inView); }
    await see('All done ✓');
    w.check(await summary() === await counts(3, 0, 1), `summary reads ${JSON.stringify(await summary())}`);
    await p.waitForTimeout(800);
    w.check(loops.length === 0, 'React reports an endless re-render once everything is approved');
  });

  await w.step('new session returns to the intake, answers kept', async () => {
    await click('New Session');
    await see('Build Newsletter System →');
    w.check(await (await field('Brand Name *')).inputValue() === BRAND, 'the intake lost the brand name');
    w.check(await go.isEnabled(), 'Build is disabled on the way back');
  });
}
