      const piece = JSON.parse(asked.slice(asked.indexOf('{'), asked.indexOf('\n\nThe user requests this revision: ')));
      const feedback = asked.slice(asked.indexOf('The user requests this revision: ') + 33, asked.indexOf('\n\nReturn ONLY'));
      revisions.push({ piece, feedback, lang });
      if (hold) await sleep(hold);
      return { ...piece, content: `Revised as asked: ${feedback}` };
