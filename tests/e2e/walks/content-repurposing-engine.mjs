const NB = '\u00a0';
const FR_HEADING = { instagram_caption: 'LÉGENDE INSTAGRAM', instagram_carousel: 'CARROUSEL INSTAGRAM', linkedin_personal: 'LINKEDIN PERSONNEL',
  linkedin_company: 'LINKEDIN ENTREPRISE', twitter_thread: 'FIL X/TWITTER', newsletter_excerpt: 'EXTRAIT DE NEWSLETTER',
  youtube_short: 'SCRIPT DE YOUTUBE SHORT', quote_graphic: 'VISUELS DE CITATION', podcast_intro: 'INTRO DE PODCAST', email_subject: 'OBJETS D’E-MAIL' };
// The label prefixes the prompt spells out come back in English and are
// shown in French. What follows the dash is the model's own.
export const frLabel = label => label
  .replace(/^Caption (\d+) - /, 'Légende $1 · ').replace(/^Slide (\d+) - /, 'Slide $1 · ').replace(/^Post (\d+) - /, 'Post $1 · ')
  .replace(/^Tweet (\d+) - /, 'Tweet $1 · ').replace(/^Short (\d+) - /, 'Short $1 · ').replace(/^Subject (\d+) - /, 'Objet $1 · ')
  .replace(/^Quote (\d+)$/, 'Citation $1').replace(/^Company Post$/, 'Post entreprise')
  .replace(/^Podcast Teaser$/, 'Teaser de podcast').replace(/^Newsletter Excerpt$/, 'Extrait de newsletter');
export function packTextFr(brand, sourceTitle, data, keys, pieces = {}) {
  const lines = [`PACK DE DÉCLINAISON DE CONTENU · ${brand}`, `Source${NB}: ${sourceTitle || 'Sans titre'}`, 'Généré par BrandOS / Phase 04', ''];
  if (data.extractedCore) { lines.push(`IDÉE CENTRALE${NB}:`); lines.push(data.extractedCore); lines.push(''); }
  if (data.contentAngles && data.contentAngles.length) {
    lines.push(`ANGLES NARRATIFS${NB}:`);
    data.contentAngles.forEach(a => { lines.push(`  ${a.angle}: ${a.description || ''} ${a.bestFor ? '→ ' + a.bestFor : ''}`.trim()); });
    lines.push('');
  }
  for (const [key] of FORMATS) {
    if (!keys.includes(key) || !(data[key] && data[key].length)) continue;
    const list = pieces[key] || data[key];
    if (!list.length) continue;
    lines.push('='.repeat(50));
    lines.push(FR_HEADING[key]);
    lines.push('='.repeat(50), '');
    list.forEach((item, i) => {
      lines.push(item.label ? frLabel(item.label) : `Élément ${i + 1}`);
      lines.push(item.content || '');
      if (item.hashtags && item.hashtags.length) lines.push(item.hashtags.map(h => '#' + h).join(' '));
      if (item.visualBrief) lines.push(`Visuel${NB}: ${item.visualBrief}`);
      if (item.note) lines.push(`Note${NB}: ${item.note}`);
      lines.push('');
    });
  }
  return lines.join('\n');
}

// A profile link the way brand-document.html builds it: base64 of the UTF-8
// bytes, not percent-encoded. Leading spaces are tried until the payload
// holds a "+", which a query string reads as a space.
export const PROFILE = {
  brandName: BRAND,
  brandEssence: 'Le pain d’abord. Le reste après.',
  archetype: 'The Sage',
  voiceNotes: 'Phrases courtes > jamais de superlatifs ?',
  primaryPersona: 'Les voisins qui achètent leur pain chaque matin.',
};
export function profileLink(profile) {
  const json = JSON.stringify(profile);
  let best = Buffer.from(json, 'utf8').toString('base64');
  for (let pad = 0; pad < 12 && !best.includes('+'); pad++) best = Buffer.from(' '.repeat(pad) + json, 'utf8').toString('base64');
  return 'qbp=' + best;
}

const UNAVAILABLE = 'Generation was unavailable. Nothing was produced. Try again in a moment.';
