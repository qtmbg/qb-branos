    try { body = JSON.parse(route.request().postData() || '{}'); } catch (e) {}
    if (revisionFails && /content revision agent/.test(body.system || '')) return json(502, {});
    if (mode === 'gateway') return json(502, {});
    if (mode === 'refused') return json(529, { error: { message: 'Overloaded' } });
    if (mode === 'bare') return json(500, {});
    if (mode === 'soft') return json(200, { error: { message: 'Quota reached' } });
    if (mode === 'empty') return json(200, { content: [] });
