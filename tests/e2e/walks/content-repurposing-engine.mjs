  const click = async (english, opts = {}) => { await (await find(english, opts)).click({ timeout: 8000 }); await p.waitForTimeout(200); };
  const absent = async (english, opts = {}) => (await find(english, opts)).waitFor({ state: 'hidden', timeout: 8000 });
  const text = async locator => flat(await locator.innerText());
  const shown = label => (w.lang === 'fr' ? frLabel(label) : label);

  const inputs = p.locator('#root main input[type="text"]'), areas = p.locator('#root main textarea'), selects = p.locator('#root main select');
  const fields = { title: inputs.nth(0), brand: inputs.nth(1), essence: inputs.nth(2), source: areas.nth(0), voice: areas.nth(1), audience: areas.nth(3), format: selects.nth(0), archetype: selects.nth(1) };
  const run = p.locator('#root button.btn-primary');
  const picker = p.locator('#root .platform-btn');
  const announced = async () => (await p.locator('#root .platform-btn.on').allInnerTexts()).reduce((sum, t) => sum + Number((/×\s*(\d+)/.exec(t) || [0, 0])[1]), 0);
