// The English pack, line for line as exportAll() has always written it.
// pieces overrides what a format holds, for a pack exported after a review.
export function packText(brand, sourceTitle, data, keys, pieces = {}) {
  const lines = [`CONTENT REPURPOSING PACK - ${brand || 'Brand'}`, `Source: ${sourceTitle || 'Untitled'}`, 'Generated by BrandOS / Phase 04', ''];
  if (data.extractedCore) { lines.push('CORE IDEA:'); lines.push(data.extractedCore); lines.push(''); }
  if (data.contentAngles && data.contentAngles.length) {
    lines.push('NARRATIVE ANGLES:');
    data.contentAngles.forEach(a => { lines.push(`  ${a.angle}: ${a.description || ''} ${a.bestFor ? '→ ' + a.bestFor : ''}`.trim()); });
    lines.push('');
  }
  for (const [key, label] of FORMATS) {
    if (!keys.includes(key) || !(data[key] && data[key].length)) continue;
    const list = pieces[key] || data[key];
    if (!list.length) continue;
    lines.push('='.repeat(50));
    lines.push(label.toUpperCase());
    lines.push('='.repeat(50), '');
    list.forEach((item, i) => {
      lines.push(item.label || `Item ${i + 1}`);
      lines.push(item.content || '');
      if (item.hashtags && item.hashtags.length) lines.push(item.hashtags.map(h => '#' + h).join(' '));
      if (item.visualBrief) lines.push(`Visual: ${item.visualBrief}`);
      if (item.note) lines.push(`Note: ${item.note}`);
      lines.push('');
    });
  }
  return lines.join('\n');
}

