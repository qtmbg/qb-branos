// YouTube Strategy Agent (operator page): the intake and its gate, every
// error the page can show, generation, the channel tab, the six videos and
// their four tabs, the review loop to its third round, copy, and the .txt
// pack read back and compared whole, in both languages.
import fs from 'node:fs';

export const page = 'youtube-strategy-agent.html';
export const title = 'intake, errors, channel, six videos, review to round 3, copy, .txt pack';

const sleep = ms => new Promise(r => setTimeout(r, ms));
const flat = s => String(s).replace(/\s+/g, ' ').trim();

// ── What the model answers ──────────────────────────────────────────────
// The page promises 3 series, 6 videos and 18 reels, so the answer holds
// exactly that. "Talking head" and "Essay" are two of the formats the prompt
// lists in English: the page paints them in French. The second act of every
// video has no title, so the page falls back to "Body section".
const BRAND = 'Maison Levain';
const video = n => ({
  videoNumber: n, series: `Series ${Math.ceil(n / 2)} name`, title: `Video ${n} title`, premise: `Video ${n} premise`,
  format: n === 1 ? 'Talking head' : n === 2 ? 'Essay' : 'Field film', duration: '9 min',
  hook: `Video ${n} hook, said to camera.\nVideo ${n} hook, second beat.`,
  intro: `Video ${n} intro`,
  body: [{ title: `Video ${n} first act`, content: `Video ${n} act one script` }, { content: `Video ${n} act two script` }, { title: `Video ${n} last act`, content: `Video ${n} act three script` }],
  transition: `Video ${n} midpoint line`, cta: `Video ${n} end card`,
  thumbnailConcept: `Video ${n} thumbnail`, thumbnailText: `Video ${n} words`, thumbnailMidjourney: `Video ${n} image prompt`,
  titleVariants: [`Video ${n} variant A`, `Video ${n} variant B`, `Video ${n} variant C`],
  description: `Video ${n} description`, tags: [`tag${n}a`, `tag${n}b`],
  reels: ['Instagram Reels', 'TikTok', 'YouTube Shorts'].map((platform, i) => ({
    angle: `Video ${n} reel ${i + 1} angle`, duration: '30-60s', platform, hookType: 'Cold open',
    hook: `Video ${n} reel ${i + 1} opening`, script: `Video ${n} reel ${i + 1} script`,
  })),
  linkedinPost: `Video ${n} as a post`, tweetThread: `Video ${n} as a thread`, newsletterAngle: `Video ${n} as an issue`,
});
const answer = () => ({
  channel: {
    positioningStatement: 'Channel statement', premise: 'Channel angle', targetViewer: 'Channel viewer',
    series: [1, 2, 3].map(i => ({ name: `Series ${i} name`, premise: `Series ${i} premise`, cadence: `Series ${i} rhythm`, pillars: [`Series ${i} pillar A`, `Series ${i} pillar B`] })),
    channelOptimizations: ['Channel fix one', 'Channel fix two'], repurposeSystem: 'Channel flywheel',
  },
  videos: [1, 2, 3, 4, 5, 6].map(video),
});

// ── The pack, restated here line for line ───────────────────────────────
const WORDS = {
  en: {
    title: b => `YOUTUBE STRATEGY PACK - ${b}`, by: 'Generated by BrandOS - YouTube Strategy Agent',
    ep: (n, t) => `EP${n} - ${t}`, meta: (s, f, d) => `Series: ${s} | Format: ${f} | ${d}`,
    hook: 'HOOK:', intro: 'INTRO:', act: (n, t) => `ACT ${n} - ${t}:`, untitled: 'Body section',
    transition: 'TRANSITION:', cta: 'CTA:', reels: 'REELS:', reel: (n, where, h) => `Reel ${n} (${where}): ${h}`, formats: {},
  },
  fr: {
    title: b => `PACK DE STRATÉGIE YOUTUBE · ${b}`, by: 'Généré par BrandOS · Agent de stratégie YouTube',
    ep: (n, t) => `EP${n} · ${t}`, meta: (s, f, d) => `Série : ${s} | Format : ${f} | ${d}`,
    hook: 'ACCROCHE :', intro: 'INTRO :', act: (n, t) => `ACTE ${n} · ${t} :`, untitled: 'Section du corps',
    transition: 'TRANSITION :', cta: 'CTA :', reels: 'REELS :', reel: (n, where, h) => `Reel ${n} (${where}) : ${h}`,
    formats: { 'Talking head': 'Face caméra', Essay: 'Essai' },
  },
};
function pack(lang, kept) {
  const L = WORDS[lang];
  const lines = [L.title(BRAND), L.by, ''];
  for (const v of kept) {
    lines.push('='.repeat(60), L.ep(String(v.videoNumber).padStart(2, '0'), v.title), L.meta(v.series, L.formats[v.format] || v.format, v.duration), '');
    lines.push(L.hook, v.hook, '', L.intro, v.intro, '');
    v.body.forEach((s, i) => lines.push(L.act(i + 1, s.title || L.untitled), s.content, ''));
    lines.push(L.transition, v.transition, '', L.cta, v.cta, '', L.reels);
    v.reels.forEach((r, i) => lines.push(L.reel(i + 1, r.platform, r.hook), r.script, ''));
    lines.push('');
  }
  return lines.join('\n');
}
const firstDifference = (got, want) => {
  const a = got.split('\n'), b = want.split('\n');
  for (let i = 0; i < Math.max(a.length, b.length); i++) if (a[i] !== b[i]) return `line ${i + 1}: got ${JSON.stringify(a[i])}, expected ${JSON.stringify(b[i])}`;
  return 'same lines, different line endings';
};

export async function walk(w) {
  const p = w.page;
  const main = { within: '#root main' };
  const calls = [];                       // every model call the page made
  let reply = null;                       // a one-off answer for the next generation
  const loops = [];
  p.on('console', m => { if (/Maximum update depth/.test(m.text())) loops.push(m.text()); });

  // w.see, w.click and w.locate cannot find French text that holds a no-break
  // space ("Acte 1 : …"): the helper turns it into a plain space on its side
  // and XPath does not on the page's side. Text with one is looked up here;
  // everything else goes through the helper as usual.
  const locate = async (english, opts = {}) => {
    const painted = opts.painted ? english : await w.say(english);
    if (!painted.includes(' ')) return w.locate(english, opts);
    const text = flat(painted);
    const lit = text.includes("'") ? `concat('${text.split("'").join(`', "'", '`)}')` : `'${text}'`;
    return (opts.within ? p.locator(opts.within) : p)
      .locator(`xpath=.//*[text()[normalize-space(translate(., ' ', ' '))=${lit}]]`).filter({ visible: true }).first();
  };
  // A failure names the text it was after, so the report says what was missing.
  const named = (what, english, e) => new Error(`${what} ${JSON.stringify(english)}: ${String(e.message).split('\n')[0]}`);
  const see = async (english, opts = {}) => {
    try { await (await locate(english, opts)).waitFor({ state: 'visible', timeout: opts.timeout ?? 8000 }); }
    catch (e) { throw named('did not see', english, e); }
  };
  const click = async (english, opts = {}) => {
    try { await (await locate(english, opts)).click({ timeout: opts.timeout ?? 8000 }); }
    catch (e) { throw named('could not click', english, e); }
    await p.waitForTimeout(opts.wait ?? 250);
  };

  // A field is the input, textarea or select that follows its label.
  const field = async label => (await locate(label)).locator('xpath=following-sibling::*[self::input or self::textarea or self::select][1]');
  const go = p.locator('#root button.btn-primary');
  const shown = '.qb-review_item:visible';                 // the one video on screen
  const inView = { within: shown };
  const pick = async i => { await p.locator('#root .ep-card').nth(i).click(); await p.waitForTimeout(200); };
  const summary = async () => flat(await p.locator('.qb-review > div:first-child > div:first-child > div:nth-child(2)').textContent());
  const counts = async (a, b, c) => `${a} ${await w.say('approved ·')} ${b} ${await w.say('pending ·')} ${c} ${await w.say('removed')}`;
  const clipboard = () => p.evaluate(() => navigator.clipboard.readText());
  const failOnce = (status, body, type = 'application/json') =>
    p.context().route('**/api/claude', async route => { await sleep(500); await route.fulfill({ status, contentType: type, body }); }, { times: 1 });

  await w.mockModel(async (body, route) => {
    const lang = route.request().headers()['x-qb-lang'];
    const text = body.messages && body.messages[0] && body.messages[0].content || '';
    if (/content revision agent/.test(body.system || '')) {
      const item = JSON.parse(/^You produced this content piece: ([\s\S]*?)\n\nThe user requests this revision: /.exec(text)[1]);
      const ask = /The user requests this revision: ([\s\S]*?)\n\nReturn ONLY/.exec(text)[1];
      calls.push({ kind: 'revise', lang, item, ask, max: body.max_tokens });
      await sleep(600);
      if (/break/.test(ask)) return 'Sorry, here is some prose and no JSON.';
      const n = /round (\d)/.exec(ask)[1];
      return { ...item, title: `Video ${item.videoNumber}, revision ${n}`, hook: `Video ${item.videoNumber} hook, revision ${n}` };
    }
    calls.push({ kind: 'generate', lang, text, system: body.system || '', max: body.max_tokens });
    await sleep(600);
    const out = reply || answer();
    reply = null;
    return out;
  });

  await w.step('open', async () => {
    await w.open();
    await see('Generate YouTube Strategy →', { timeout: 45000 });
    await see('YouTube Strategy Agent', main);
    await see('// Phase 03 - Content Creation');
    w.check(await p.title() === await w.say('YouTube Strategy Agent · BrandOS'), `title tag is ${JSON.stringify(await p.title())}`);
  });

  await w.step('intake: the button opens on the six required fields, the host is optional', async () => {
    w.check(await go.isDisabled(), 'Generate is enabled on an empty form');
    await see('Host Name');                       // no asterisk: the form does not require it
    w.check(await (await field('Brand Name *')).getAttribute('placeholder') === await w.say('The brand behind the channel'), 'input placeholder is not in the page language');
    w.check(await (await field('Brand Essence *')).getAttribute('placeholder') === await w.say('Irreducible truth'), 'textarea placeholder is not in the page language');
    await w.fill(await field('Brand Name *'), BRAND);
    await w.fill(await field('Brand Essence *'), 'Bread, and nothing else.');
    const force = await field('Natural Force *');
    await force.selectOption('The River');
    w.check(flat(await force.locator('option:checked').innerText()) === await w.say('The River'), 'the chosen force is not painted in the page language');
    await (await field('Primary Archetype *')).selectOption('The Creator');
    await w.fill(await field('Primary Persona *'), 'Parents who cook on Sunday.');
    w.check(await go.isDisabled(), 'Generate is enabled with the offer still empty');
    await w.fill(await field('Core Offer *'), 'A weekly bread subscription.');
    w.check(await go.isEnabled(), 'Generate is still disabled with every required field filled and no host');
    await w.fill(await field('Brand Name *'), '');
    w.check(await go.isDisabled(), 'Generate stays enabled after a required field is emptied');
    await w.fill(await field('Brand Name *'), BRAND);
  });

  const fails = async (name, arm, message) => {
    await w.step(`error: ${name}`, async () => {
      await arm();
      await go.click();
      await see('Agent Processing');
      await see(message, { timeout: 10000 });
      w.check(await (await field('Brand Name *')).inputValue() === BRAND, 'the form was emptied by the error');
      w.check(await go.isEnabled(), 'Generate is not available after the error');
    });
  };
  const gone = 'The agent could not finish. Nothing was generated. Try again in a moment.';
  w.note('Overloaded, try later');
  w.note('Plain refusal');
  await fails('the server answers 500 with a message', () => failOnce(500, JSON.stringify({ error: { message: 'Overloaded, try later' } })), 'Agent error: AI service error: Overloaded, try later');
  await fails('the server answers 500 with nothing', () => failOnce(500, '{}'), 'Agent error: AI service error: HTTP 500');
  await fails('the gateway times out', () => failOnce(504, 'timeout', 'text/plain'), gone);
  await fails('the answer is not JSON', () => failOnce(200, '<html>oops</html>', 'text/html'), gone);
  await fails('the answer is an error with no message', () => failOnce(200, JSON.stringify({ error: {} })), 'Agent error: AI request failed');
  await fails('the answer is an error in plain words', () => failOnce(200, JSON.stringify({ error: 'Plain refusal' })), 'Agent error: Plain refusal');
  await fails('the model writes prose', async () => { reply = 'Here is your channel, in prose.'; }, gone);
  await fails('no video comes back', async () => { reply = { channel: answer().channel, videos: [] }; }, 'Agent error: AI returned no videos');

  await w.step('generate', async () => {
    await go.click();
    await see('Agent Processing');
    await see('Weaving identity into narrative architecture...');
    await see('3 series · 6 scripts · 18 reels · full repurpose');
    await see('// YouTube Strategy - Complete', { timeout: 10000 });
    await see('3 series · 6 videos · 18 reels · complete repurpose system');
    const call = calls.filter(c => c.kind === 'generate').pop();
    w.check(call.lang === w.lang, `the model was asked in ${JSON.stringify(call.lang)}, not ${w.lang}`);
    // What goes to the model stays English whatever the page shows.
    w.check(call.text.includes('Natural Force: The River') && call.text.includes('Archetype: The Creator'), 'the prompt did not carry the stored English values');
    w.check(call.text.includes(`Brand: ${BRAND}`) && call.text.includes('Founder / Host: [Host]'), 'the prompt did not carry the intake');
  });

  await w.step('channel strategy', async () => {
    for (const label of ['Channel positioning statement', 'Channel premise', 'Target viewer', 'Series', 'Channel page optimizations', 'Repurpose flywheel']) await see(label, main);
    for (const text of ['Channel angle', 'Channel viewer', 'Series 3 name', 'Series 3 pillar B', 'Channel fix two', 'Channel flywheel']) await see(text, { painted: true });
    w.check(await p.locator('#root main .glass-card').filter({ hasText: await w.say('Series') }).count() >= 3, 'fewer than three series cards');
  });

  await w.step('six videos, one on screen, under review', async () => {
    await click('Scripts + Repurpose');
    await see('6 videos - select to view');
    await see('Content Review');
    w.check(await p.locator('#root .ep-card').count() === 6, 'the list does not hold 6 videos');
    w.check(await p.locator('.qb-review_item').count() === 6 && await p.locator(shown).count() === 1, 'the review does not show one video of six');
    w.check(await summary() === await counts(0, 6, 0), `summary reads ${JSON.stringify(await summary())}`);
    await see('Video 1 title', { painted: true, within: shown });
    await see(await w.say('Talking head'), { painted: true, within: shown });
    await see('Pending review', inView);
  });

  await w.step('video 1: script, thumbnail, repurpose, metadata, and copy', async () => {
    await see('Hook - first 30 seconds', inView);                 // open from the start
    await click('Copy', inView);
    await see('Copied ✓', inView);
    w.check(await clipboard() === video(1).hook, `the clipboard holds ${JSON.stringify(await clipboard())}`);
    await click('Intro - context + promise', inView);
    await see('Video 1 intro', { painted: true, within: shown });
    await see('Act 1 - Video 1 first act', inView);
    await see('Act 2 - Body section', inView);                    // the act with no title
    await click('Act 2 - Body section', inView);
    await see('Video 1 act two script', { painted: true, within: shown });
    await see('Transition / midpoint', inView);
    await see('CTA - end card', inView);

    await click('thumbnail', inView);
    for (const label of ['Thumbnail concept', 'On-image text', 'Midjourney prompt', 'Title variants - A/B test these']) await see(label, inView);
    await see('Video 1 variant C', { painted: true, within: shown });

    await click('Repurpose', inView);
    const line = await locate('One video →', inView);
    const tally = `${await w.say('One video →')} 6 ${await w.say('repurposed assets. Same intelligence, different surfaces.')}`;
    w.check(flat(await line.textContent()) === flat(tally), `the tally reads ${JSON.stringify(flat(await line.textContent()))}`);
    for (const label of ['Reel / Short', 'Hook', 'Script', 'LinkedIn post - from this video', 'Tweet thread - from this video', 'Newsletter angle']) await see(label, inView);
    for (const text of ['YouTube Shorts', 'Video 1 reel 3 script', 'Video 1 as a post', 'Video 1 as a thread', 'Video 1 as an issue']) await see(text, { painted: true, within: shown });

    await click('metadata', inView);
    await see('Video description (YouTube)', inView);
    await see('Tags', inView);
    await see('Video 1 description', { painted: true, within: shown });
    await click('script', inView);
  });

  await w.step('the list picks the video', async () => {
    await pick(1);
    await see('Video 2 title', { painted: true, within: shown });
    await see(await w.say('Essay'), { painted: true, within: shown });
    w.check(await p.locator(shown).count() === 1, 'more than one video on screen');
    w.check(!flat(await p.locator(shown).innerText()).includes('Video 1 title'), 'video 1 is still on screen');
    await pick(0);
  });

  await w.step('review: three rounds on one video, then no fourth', async () => {
    for (const round of [1, 2, 3]) {
      await click('↻ Revise', inView);
      const head = await locate('REVISION REQUEST', inView);
      w.check(flat(await head.textContent()) === `${await w.say('REVISION REQUEST')} ${round}/3`, `the request header reads ${JSON.stringify(flat(await head.textContent()))}`);
      const box = p.locator(shown).locator('textarea');
      if (round === 1) w.check(await box.getAttribute('placeholder') === await w.say('What should change? Be specific...'), 'the request placeholder is not in the page language');
      await w.fill(box, `Tighter, round ${round}`);
      await click('Submit Revision →', { within: shown, wait: 50 });
      await see('Revising…', inView);
      await see('Generating revision…', inView);
      await see('Revised - review again', inView);
      await see(`(Round ${round}/3)`, inView);
      await see(`Video 1, revision ${round}`, { painted: true, within: shown });
      // The list beside it follows the revision.
      await see(`Video 1, revision ${round}`, { painted: true, within: '#root .ep-card >> nth=0' });
    }
    w.check(await (await locate('↻ Revise', inView)).count() === 0, 'a fourth revision is offered');
    w.check(await (await locate('✓ Approve', inView)).count() === 1, 'Approve is gone after the third round');
    const asks = calls.filter(c => c.kind === 'revise');
    w.check(asks.length === 3, `${asks.length} revision calls for three rounds`);
    w.check(asks.every(c => c.lang === w.lang), 'a revision was not asked in the page language');
    w.check(asks[2] && asks[2].item.title === 'Video 1, revision 2' && asks[2].ask === 'Tighter, round 3', 'the third round did not start from the second');
    // A whole video does not fit in the 1000 tokens a short post gets.
    w.check(asks.every(c => c.max === 8000), `revision budget was ${asks.map(c => c.max).join(', ')}`);
  });

  await w.step('review: cancel, a failed revision, remove, approve, undo', async () => {
    await pick(1);
    await click('↻ Revise', inView);
    await click('Cancel', inView);
    w.check(await p.locator(shown).locator('textarea').count() === 0, 'Cancel left the request open');

    await click('↻ Revise', inView);
    await w.fill(p.locator(shown).locator('textarea'), 'Please break');
    await click('Submit Revision →', { within: shown, wait: 50 });
    await see('Revising…', inView);
    await see('Revision failed - try again', inView);
    await see('Video 2 title', { painted: true, within: shown });
    await click('↻ Revise', inView);
    w.check(flat(await (await locate('REVISION REQUEST', inView)).textContent()).endsWith(' 1/3'), 'a failed revision used up a round');
    await click('Cancel', inView);

    await pick(2);
    await click('× Remove', inView);
    await see('Removed', inView);
    await p.waitForTimeout(500);                                   // the card fades
    w.check(await p.locator('#root .ep-card').nth(2).evaluate(el => getComputedStyle(el).opacity) === '0.4', 'the removed video is not dimmed in the list');

    await pick(0);
    await click('✓ Approve', inView);
    await see('✓ Approved', inView);
    w.check(await summary() === await counts(1, 4, 1), `summary reads ${JSON.stringify(await summary())}`);
    await click('Undo', inView);
    await see('Pending review', inView);
    w.check(await summary() === await counts(0, 5, 1), `summary reads ${JSON.stringify(await summary())}`);
  });

  await w.step('the review survives a change of tab', async () => {
    await click('Channel Strategy');
    await see('Channel premise', main);
    await click('Scripts + Repurpose');
    await see('Video 1, revision 3', { painted: true, within: shown });
    w.check(await summary() === await counts(0, 5, 1), `after the round trip the summary reads ${JSON.stringify(await summary())}`);
  });

  await w.step('the .txt pack holds what the review holds', async () => {
    const [dl] = await Promise.all([p.waitForEvent('download', { timeout: 10000 }), click('Export Scripts')]);
    const file = { name: dl.suggestedFilename(), text: fs.readFileSync(await dl.path(), 'utf8') };
    const kept = answer().videos.filter(v => v.videoNumber !== 3)
      .map(v => v.videoNumber === 1 ? { ...v, title: 'Video 1, revision 3', hook: 'Video 1 hook, revision 3' } : v);
    const want = pack(w.lang, kept);
    w.check(file.name === 'maison-levain-youtube-strategy.txt', `the file is named ${JSON.stringify(file.name)}`);
    w.check(file.text === want, `the pack differs at ${firstDifference(file.text, want)}`);
    w.check(!file.text.includes('Video 3'), 'a removed video is in the pack');
    w.check(file.text.includes('Video 1 midpoint line'), 'the midpoint transition is not in the pack');
  });

  await w.step('approve everything: all done, and the page comes to rest', async () => {
    for (const i of [0, 1, 3, 4, 5]) { await pick(i); await click('✓ Approve', inView); }
    await see('All done ✓');
    w.check(await summary() === await counts(5, 0, 1), `summary reads ${JSON.stringify(await summary())}`);
    await p.waitForTimeout(800);
    w.check(loops.length === 0, 'React reports an endless re-render once everything is approved');
  });

  await w.step('new strategy returns to the intake, answers kept', async () => {
    await click('New Strategy');
    await see('Generate YouTube Strategy →');
    w.check(await (await field('Brand Name *')).inputValue() === BRAND, 'the intake lost the brand name');
    w.check(await go.isEnabled(), 'Generate is disabled on the way back');
  });
}
