// LinkedIn Strategy Agent (operator page): the intake and its gate, every
// error the page can show, generation, both accounts and their three tabs,
// the review loop to its third round, copy, and the .txt pack read back and
// compared whole, in both languages.
import fs from 'node:fs';

export const page = 'linkedin-strategy-agent.html';
export const title = 'intake, errors, two accounts, review to round 3, copy, .txt pack';

const sleep = ms => new Promise(r => setTimeout(r, ms));
const flat = s => String(s).replace(/\s+/g, ' ').trim();

// ── What the model answers ──────────────────────────────────────────────
// The page promises 12 founder posts and 8 company posts over 4 weeks, so
// the answer holds exactly that. "Belief post" and "bold statement" are two
// of the values the prompt lists in English: the page paints them in French.
const BRAND = 'Maison Levain';
const post = (who, n, week) => ({
  postNumber: n, week, dayNumber: n,
  weekTheme: `${who} theme ${week}`, weekIntent: `${who} intent ${week}`,
  postTitle: `${who} post ${n} title`,
  postType: n === 1 ? 'Belief post' : 'Field note',
  contentPillar: `${who} pillar`,
  hook: `${who} hook ${n}`, hookType: 'bold statement',
  fullPost: `${who} post ${n}, first line.\n\n${who} post ${n}, second line.`,
  strategicPurpose: `${who} purpose ${n}`, cta: `${who} call ${n}`,
  hashtags: ['levain', 'bakery'], bestTime: 'Tuesday 8am',
});
const side = (who, count, perWeek) => ({
  profile: {
    headline: `${who} headline`, about: `${who} about, line one.\n${who} about, line two.`,
    featuredSection: `${who} featured`, bannerDirection: `${who} banner`, profilePhotoDirection: `${who} photo`,
    experiencePositioning: `${who} experience`, connectionStrategy: `${who} connections`,
  },
  strategy: {
    positioning: `${who} positioning`,
    contentPillars: [1, 2, 3, 4].map(i => ({ pillar: `${who} pillar ${i}`, why: `${who} reason ${i}` })),
    cadence: `${who} cadence`, audienceTarget: `${who} audience`, uniqueEdge: `${who} edge`,
    weeklyThemes: [1, 2, 3, 4].map(i => ({ theme: `${who} theme ${i}`, intent: `${who} intent ${i}` })),
  },
  posts: Array.from({ length: count }, (_, i) => post(who, i + 1, Math.floor(i / perWeek) + 1)),
});
const answer = () => ({ personal: side('Ines', 12, 3), company: side('Levain', 8, 2) });

// ── The pack, restated here line for line ───────────────────────────────
// English must match what exportAll() has always written. French is the
// same file with its labels in French and the founder's lines untouched.
const WORDS = {
  en: {
    title: b => `LINKEDIN STRATEGY PACK - ${b}`, by: 'Generated by BrandOS - LinkedIn Strategy Agent',
    personal: f => `PERSONAL PROFILE - ${f}`, company: b => `COMPANY PAGE - ${b}`, founder: 'Founder',
    headline: 'HEADLINE:', about: 'ABOUT:', posts: 'POSTS:',
    post: (wk, n, t) => `Week ${wk} · Post ${n} - ${t}`, type: t => `Type: ${t}`, types: {},
  },
  fr: {
    title: b => `PACK DE STRATÉGIE LINKEDIN · ${b}`, by: 'Généré par BrandOS · Agent de stratégie LinkedIn',
    personal: f => `PROFIL PERSONNEL · ${f}`, company: b => `PAGE ENTREPRISE · ${b}`, founder: 'Fondateur',
    headline: 'TITRE :', about: 'INFOS :', posts: 'POSTS :',
    post: (wk, n, t) => `Semaine ${wk} · Post ${n} · ${t}`, type: t => `Type : ${t}`,
    types: { 'Belief post': 'Post de conviction' },
  },
};
function pack(lang, data, kept) {
  const L = WORDS[lang];
  const lines = [L.title(BRAND), L.by, ''];
  for (const m of ['personal', 'company']) {
    lines.push('='.repeat(60), m === 'personal' ? L.personal(L.founder) : L.company(BRAND), '='.repeat(60), '');
    lines.push(L.headline, data[m].profile.headline, '');
    lines.push(L.about, data[m].profile.about, '');
    lines.push('-'.repeat(40), L.posts, '');
    for (const p of kept[m]) {
      lines.push(L.post(p.week, p.postNumber, p.postTitle), L.type(L.types[p.postType] || p.postType), '', p.fullPost, '');
      lines.push(p.hashtags.map(h => '#' + h).join(' '), '', '-'.repeat(40), '');
    }
  }
  return lines.join('\n');
}
const firstDifference = (got, want) => {
  const a = got.split('\n'), b = want.split('\n');
  for (let i = 0; i < Math.max(a.length, b.length); i++) if (a[i] !== b[i]) return `line ${i + 1}: got ${JSON.stringify(a[i])}, expected ${JSON.stringify(b[i])}`;
  return 'same lines, different line endings';
};

export async function walk(w) {
  const p = w.page;
  const main = { within: '#root main' };
  const calls = [];                       // every model call the page made
  let reply = null;                       // a one-off answer for the next generation
  const loops = [];
  p.on('console', m => { if (/Maximum update depth/.test(m.text())) loops.push(m.text()); });

  // w.see, w.click and w.locate cannot find French text that holds a no-break
  // space ("Type d’accroche :"): the helper turns it into a plain space on
  // its side and XPath does not on the page's side. Text with one is looked
  // up here; everything else goes through the helper as usual.
  const locate = async (english, opts = {}) => {
    const painted = opts.painted ? english : await w.say(english);
    if (!painted.includes('\u00a0')) return w.locate(english, opts);
    const text = flat(painted);
    const lit = text.includes("'") ? `concat('${text.split("'").join(`', "'", '`)}')` : `'${text}'`;
    return (opts.within ? p.locator(opts.within) : p)
      .locator(`xpath=.//*[text()[normalize-space(translate(., '\u00a0', ' '))=${lit}]]`).filter({ visible: true }).first();
  };
  // A failure names the text it was after, so the report says what was missing.
  const named = (what, english, e) => new Error(`${what} ${JSON.stringify(english)}: ${String(e.message).split('\n')[0]}`);
  const see = async (english, opts = {}) => {
    try { await (await locate(english, opts)).waitFor({ state: 'visible', timeout: opts.timeout ?? 8000 }); }
    catch (e) { throw named('did not see', english, e); }
  };
  const click = async (english, opts = {}) => {
    try { await (await locate(english, opts)).click({ timeout: opts.timeout ?? 8000 }); }
    catch (e) { throw named('could not click', english, e); }
    await p.waitForTimeout(opts.wait ?? 250);
  };

  // A field is the input, textarea or select that follows its label.
  const field = async label => (await locate(label)).locator('xpath=following-sibling::*[self::input or self::textarea or self::select][1]');
  const go = p.locator('#root button.btn-primary');
  const card = (m, i) => `[data-review="${m}"] .qb-review_item >> nth=${i}`;
  const summary = async m => flat(await p.locator(`[data-review="${m}"] .qb-review > div:first-child > div:first-child > div:nth-child(2)`).textContent());
  const counts = async (a, b, c) => `${a} ${await w.say('approved ·')} ${b} ${await w.say('pending ·')} ${c} ${await w.say('removed')}`;
  const clipboard = () => p.evaluate(() => navigator.clipboard.readText());
  const failOnce = (status, body, type = 'application/json') =>
    p.context().route('**/api/claude', async route => { await sleep(500); await route.fulfill({ status, contentType: type, body }); }, { times: 1 });

  await w.mockModel(async (body, route) => {
    const lang = route.request().headers()['x-qb-lang'];
    const text = body.messages && body.messages[0] && body.messages[0].content || '';
    if (/content revision agent/.test(body.system || '')) {
      const item = JSON.parse(/^You produced this content piece: ([\s\S]*?)\n\nThe user requests this revision: /.exec(text)[1]);
      const ask = /The user requests this revision: ([\s\S]*?)\n\nReturn ONLY/.exec(text)[1];
      calls.push({ kind: 'revise', lang, item, ask, max: body.max_tokens });
      await sleep(600);
      if (/break/.test(ask)) return 'Sorry, here is some prose and no JSON.';
      const who = item.postTitle.split(' ')[0], n = /round (\d)/.exec(ask)[1];
      return { ...item, postTitle: `${who} post ${item.postNumber}, revision ${n}`, fullPost: `${who} post ${item.postNumber}, revision ${n}, body.` };
    }
    calls.push({ kind: 'generate', lang, text, max: body.max_tokens });
    await sleep(600);
    const out = reply || answer();
    reply = null;
    return out;
  });

  await w.step('open', async () => {
    await w.open();
    await see('Generate Strategy', { timeout: 45000 });
    await see('LinkedIn Strategy Agent', main);
    await see('// Phase 03 - Content Creation');
    w.check(await p.title() === await w.say('LinkedIn Strategy Agent · BrandOS'), `title tag is ${JSON.stringify(await p.title())}`);
  });

  await w.step('intake: the button opens only when the six required fields are filled', async () => {
    w.check(await go.isDisabled(), 'Generate is enabled on an empty form');
    w.check(await (await field('Brand Name *')).getAttribute('placeholder') === await w.say('The practice / company name'), 'input placeholder is not in the page language');
    w.check(await (await field('Brand Essence *')).getAttribute('placeholder') === await w.say('The irreducible truth'), 'textarea placeholder is not in the page language');
    await w.fill(await field('Brand Name *'), BRAND);
    await w.fill(await field('Brand Essence *'), 'Bread, and nothing else.');
    const force = await field('Natural Force *');
    await force.selectOption('Wildfire');
    w.check(flat(await force.locator('option:checked').innerText()) === await w.say('Wildfire'), 'the chosen force is not painted in the page language');
    await (await field('Primary Archetype *')).selectOption('The Sage');
    await w.fill(await field('Core Offer *'), 'A weekly bread subscription.');
    w.check(await go.isDisabled(), 'Generate is enabled with the persona still empty');
    await w.fill(await field('Primary Persona *'), 'Parents who cook on Sunday.');
    w.check(await go.isEnabled(), 'Generate is still disabled with every required field filled');
    await w.fill(await field('Brand Essence *'), '');
    w.check(await go.isDisabled(), 'Generate stays enabled after a required field is emptied');
    await w.fill(await field('Brand Essence *'), 'Bread, and nothing else.');
    // Founder Name is left empty on purpose: the page falls back to "Founder".
  });

  const fails = async (name, arm, message, painted) => {
    await w.step(`error: ${name}`, async () => {
      await arm();
      await go.click();
      await see('Agent Processing');
      await see(message, { painted, timeout: 10000 });
      w.check(await (await field('Brand Name *')).inputValue() === BRAND, 'the form was emptied by the error');
      w.check(await go.isEnabled(), 'Generate is not available after the error');
    });
  };
  const gone = 'The agent could not finish. Nothing was generated. Try again in a moment.';
  w.note('Overloaded, try later');
  await fails('the server answers 500 with a message', () => failOnce(500, JSON.stringify({ error: { message: 'Overloaded, try later' } })), 'Agent error: Overloaded, try later');
  await fails('the server answers 500 with nothing', () => failOnce(500, '{}'), 'Agent error: API error: HTTP 500');
  await fails('the gateway times out', () => failOnce(504, 'timeout', 'text/plain'), gone);
  await fails('the answer is not JSON', () => failOnce(200, '<html>oops</html>', 'text/html'), gone);
  await fails('the model writes prose', async () => { reply = 'Here is your strategy, in prose.'; }, gone);
  await fails('an account is missing', async () => { reply = { personal: side('Ines', 12, 3) }; }, 'Agent error: Unexpected response structure - missing personal or company keys');
  await fails('posts are not a list', async () => { reply = { personal: { posts: 'none' }, company: { posts: [] } }; }, 'Agent error: Unexpected response structure - posts must be arrays');

  await w.step('generate', async () => {
    await go.click();
    await see('Agent Processing');
    await see('Writing 12 founder posts in brand voice');
    await see('2 PROFILES · 20 POSTS · 4-WEEK ARC');
    await see('// Strategy Complete', { timeout: 10000 });
    await see('2 profiles rewritten · 20 posts scripted · 4-week arc');
    const call = calls.filter(c => c.kind === 'generate').pop();
    w.check(call.lang === w.lang, `the model was asked in ${JSON.stringify(call.lang)}, not ${w.lang}`);
    // What goes to the model stays English whatever the page shows.
    w.check(call.text.includes('Natural Force: Wildfire') && call.text.includes('Archetype: The Sage'), 'the prompt did not carry the stored English values');
    w.check(call.text.includes(`Brand: ${BRAND}`) && call.text.includes('Founder: [Founder]'), 'the prompt did not carry the intake');
  });

  await w.step('founder account: strategy', async () => {
    await see('Founder');                                   // the fallback name on the account tab
    for (const label of ['Strategic positioning', 'Content pillars', 'Cadence', 'Audience to target', 'Unique edge - what makes this account unmistakable', '4-week arc themes']) await see(label, main);
    for (const text of ['Ines positioning', 'Ines pillar 4', 'Ines cadence', 'Ines audience', 'Ines edge', 'Ines theme 4']) await see(text, { painted: true });
    w.check(flat(await p.locator('#root main').innerText()).includes(`12 ${await w.say('posts')}`), 'the counter does not read 12 posts');
  });

  await w.step('founder account: profile rewrite, and copy', async () => {
    await click('Profile Rewrite');
    for (const label of ['Headline', 'About / Summary', 'Featured section strategy', 'Banner / cover image direction', 'Profile photo direction', 'Experience section positioning', 'Connection + engagement strategy']) await see(label);
    await see('Ines headline', { painted: true });
    await click('Copy');
    await see('Copied ✓');
    w.check(await clipboard() === 'Ines headline', `the clipboard holds ${JSON.stringify(await clipboard())}`);
  });

  await w.step('founder account: 12 posts under review', async () => {
    await click('4-Week Posts');
    await see('Content Review');
    w.check(await p.locator('[data-review="personal"] .qb-review_item').count() === 12, 'the review does not hold 12 posts');
    w.check(await summary('personal') === await counts(0, 12, 0), `summary reads ${JSON.stringify(await summary('personal'))}`);
    await see('W1', { within: card('personal', 0) });
    await see('W4', { within: card('personal', 11) });
    await click('Ines post 1 title', { painted: true });
    for (const label of ['Opening hook', 'Hook type:', 'Full post', 'Strategic purpose', 'Call to Action', 'Hashtags', 'Best time:']) await see(label, { within: card('personal', 0) });
    await see(await w.say('Belief post'), { painted: true, within: card('personal', 0) });
    await see(await w.say('bold statement'), { painted: true, within: card('personal', 0) });
    await click('Copy', { within: card('personal', 0) });
    await see('Copied ✓', { within: card('personal', 0) });
    // Two paragraphs, as the model wrote them: nothing in them is a label.
    w.check(await clipboard() === post('Ines', 1, 1).fullPost, `the clipboard holds ${JSON.stringify(await clipboard())}`);
  });

  await w.step('review: three rounds on one post, then no fourth', async () => {
    const one = card('personal', 0);
    for (const round of [1, 2, 3]) {
      await click('↻ Revise', { within: one });
      const head = await locate('REVISION REQUEST', { within: one });
      w.check(flat(await head.textContent()) === `${await w.say('REVISION REQUEST')} ${round}/3`, `the request header reads ${JSON.stringify(flat(await head.textContent()))}`);
      const box = p.locator(one).locator('textarea');
      if (round === 1) w.check(await box.getAttribute('placeholder') === await w.say("What should change? Be specific: e.g. 'Make the hook more direct' or 'Remove the question format'"), 'the request placeholder is not in the page language');
      await w.fill(box, `Sharper, round ${round}`);
      await click('Submit Revision →', { within: one, wait: 50 });
      await see('Revising…', { within: one });
      await see('Generating revision…', { within: one });
      await see('Revised - review again', { within: one });
      await see(`(Round ${round}/3)`, { within: one });
      await see(`Ines post 1, revision ${round}`, { painted: true, within: one });
    }
    w.check(await (await locate('↻ Revise', { within: one })).count() === 0, 'a fourth revision is offered');
    w.check(await (await locate('✓ Approve', { within: one })).count() === 1, 'Approve is gone after the third round');
    const asks = calls.filter(c => c.kind === 'revise');
    w.check(asks.length === 3, `${asks.length} revision calls for three rounds`);
    w.check(asks.every(c => c.lang === w.lang), 'a revision was not asked in the page language');
    // Each round revises the last version, not the first draft.
    w.check(asks[2] && asks[2].item.postTitle === 'Ines post 1, revision 2' && asks[2].ask === 'Sharper, round 3', 'the third round did not start from the second');
  });

  await w.step('review: cancel, a failed revision, remove, approve, undo', async () => {
    const two = card('personal', 1), three = card('personal', 2);
    await click('↻ Revise', { within: two });
    await click('Cancel', { within: two });
    w.check(await p.locator(two).locator('textarea').count() === 0, 'Cancel left the request open');

    await click('↻ Revise', { within: two });
    await w.fill(p.locator(two).locator('textarea'), 'Please break');
    await click('Submit Revision →', { within: two, wait: 50 });
    await see('Revising…', { within: two });
    await see('Revision failed - try again', { within: two });
    await see('Ines post 2 title', { painted: true, within: two });
    // The failed call did not use a round: the next request is still 1 of 3.
    await click('↻ Revise', { within: two });
    w.check(flat(await (await locate('REVISION REQUEST', { within: two })).textContent()).endsWith(' 1/3'), 'a failed revision used up a round');
    await click('Cancel', { within: two });

    await click('× Remove', { within: three });
    await see('Removed', { within: three });
    await click('✓ Approve', { within: card('personal', 0) });
    await see('✓ Approved', { within: card('personal', 0) });
    w.check(await summary('personal') === await counts(1, 10, 1), `summary reads ${JSON.stringify(await summary('personal'))}`);
    await click('Undo', { within: card('personal', 0) });
    await see('Pending review', { within: card('personal', 0) });
    w.check(await summary('personal') === await counts(0, 11, 1), `summary reads ${JSON.stringify(await summary('personal'))}`);
  });

  await w.step('the review survives a change of tab and of account', async () => {
    await click('↻ Revise', { within: card('personal', 3) });     // left open on purpose
    await click('Strategy', main);
    await see('Strategic positioning', main);
    await click('- Company');
    await see('Levain positioning', { painted: true });
    w.check(flat(await p.locator('#root main').innerText()).includes(`8 ${await w.say('posts')}`), 'the counter does not read 8 posts');
    await click('Profile Rewrite');
    await see('Levain headline', { painted: true });
    await click('4-Week Posts');
    w.check(await p.locator('[data-review="company"] .qb-review_item').count() === 8, 'the company review does not hold 8 posts');
    w.check(await summary('company') === await counts(0, 8, 0), `company summary reads ${JSON.stringify(await summary('company'))}`);
    // A request is open on the founder side. This one must still go through.
    const one = card('company', 0);
    await click('↻ Revise', { within: one });
    await w.fill(p.locator(one).locator('textarea'), 'Warmer, round 1');
    await click('Submit Revision →', { within: one, wait: 50 });
    await see('Levain post 1, revision 1', { painted: true, within: one, timeout: 10000 });
    await click('- Personal');
    await click('4-Week Posts');
    await see('Ines post 1, revision 3', { painted: true });
    await see('Removed', { within: card('personal', 2) });
    w.check(await summary('personal') === await counts(0, 11, 1), `after the round trip the summary reads ${JSON.stringify(await summary('personal'))}`);
    w.check(await p.locator(card('personal', 3)).locator('textarea').count() === 1, 'the open request was lost on the way');
    await click('Cancel', { within: card('personal', 3) });
  });

  let file;
  await w.step('the .txt pack holds what the review holds', async () => {
    const [dl] = await Promise.all([p.waitForEvent('download', { timeout: 10000 }), click('Export All')]);
    file = { name: dl.suggestedFilename(), text: fs.readFileSync(await dl.path(), 'utf8') };
    const data = answer();
    const kept = {
      personal: data.personal.posts.filter(x => x.postNumber !== 3).map(x => x.postNumber === 1 ? { ...x, postTitle: 'Ines post 1, revision 3', fullPost: 'Ines post 1, revision 3, body.' } : x),
      company: data.company.posts.map(x => x.postNumber === 1 ? { ...x, postTitle: 'Levain post 1, revision 1', fullPost: 'Levain post 1, revision 1, body.' } : x),
    };
    const want = pack(w.lang, data, kept);
    w.check(file.name === 'maison-levain-linkedin-strategy.txt', `the file is named ${JSON.stringify(file.name)}`);
    w.check(file.text === want, `the pack differs at ${firstDifference(file.text, want)}`);
    w.check(!file.text.includes('Ines post 3'), 'a removed post is in the pack');
  });

  await w.step('approve everything: all done, and the page comes to rest', async () => {
    for (let i = 0; i < 12; i++) {
      const btn = await locate('✓ Approve', { within: '[data-review="personal"]' });
      if (!await btn.count()) break;
      await btn.click();
    }
    await see('All done ✓');
    w.check(await summary('personal') === await counts(11, 0, 1), `summary reads ${JSON.stringify(await summary('personal'))}`);
    await p.waitForTimeout(800);
    w.check(loops.length === 0, 'React reports an endless re-render once everything is approved');
  });

  await w.step('new strategy returns to the intake, answers kept', async () => {
    await click('New Strategy');
    await see('Generate Strategy');
    w.check(await (await field('Brand Name *')).inputValue() === BRAND, 'the intake lost the brand name');
    w.check(await go.isEnabled(), 'Generate is disabled on the way back');
  });
}
