/* The Final Brief (Sec 06) is one preformatted text node. A key is matched
   with its whitespace collapsed, so the log is one pattern per shape: the
   Direction and Allergic lines each carry zero to four markers joined by
   " / ". Markers are captured one by one so each is painted in French.
   Longest first, for the reason given above. */
(function () {
  var RULE = '======================================================';
  var NB = String.fromCharCode(160);   // no-break space, before the colon
  function slots(count, from) {
    var out = [];
    for (var i = 0; i < count; i++) out.push('{' + (from + i) + '}');
    return out.join(' / ');
  }
  function box(inner) { return inner ? '[ ' + inner + ' ]' : '[ ]'; }
  var entries = {};
  for (var s = 4; s >= 0; s--) {
    for (var f = 4; f >= 0; f--) {
      var sig = box(slots(s, 1));
      var temp = '[ {' + (s + 1) + '} ]';
      var energy = '[ {' + (s + 2) + '} ]';
      var fast = box(slots(f, s + 3));
      var shadow = '[ {' + (s + f + 3) + '} ]';
      var key = '>> SYSTEM LOG: VISUAL DNA BRIEF >> CLIENT: {0} ' + RULE +
        ' // VISUAL IDENTITY PARAMETERS Direction: ' + sig +
        ' Temperature: ' + temp +
        ' Core Energy: ' + energy +
        ' // THE ANTI-PATTERN BLOCKLIST Allergic: ' + fast +
        ' Shadow Warning: ' + shadow + ' ' + RULE + ' >> END OF LOG';
      entries[key] =
        '>> JOURNAL SYSTÈME' + NB + ': BRIEF VISUAL DNA\n' +
        '>> CLIENT' + NB + ': {0}\n' +
        RULE + '\n\n' +
        '// PARAMÈTRES D’IDENTITÉ VISUELLE\n' +
        'Direction' + NB + ':        ' + sig + '\n' +
        'Température' + NB + ':      ' + temp + '\n' +
        'Énergie centrale' + NB + ': ' + energy + '\n\n' +
        '// LISTE NOIRE DES ANTI-MOTIFS\n' +
        'Allergies' + NB + ':        ' + fast + '\n' +
        'Alerte ombre' + NB + ':     ' + shadow + '\n\n' +
        RULE + '\n' +
        '>> FIN DU JOURNAL';
    }
  }
  QBI18N.add('fr', entries);
})();
